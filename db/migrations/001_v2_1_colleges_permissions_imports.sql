CREATE FUNCTION attendance.set_college_from_department() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    SELECT d.college_id INTO NEW.college_id
      FROM attendance.departments d
     WHERE d.department_id = NEW.department_id;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_subjects_college BEFORE INSERT OR UPDATE OF department_id, college_id ON attendance.subjects
    FOR EACH ROW EXECUTE FUNCTION attendance.set_college_from_department();
CREATE TRIGGER trg_staff_college BEFORE INSERT OR UPDATE OF department_id, college_id ON attendance.staff
    FOR EACH ROW EXECUTE FUNCTION attendance.set_college_from_department();

CREATE FUNCTION identity.set_student_college() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NEW.section_id IS NOT NULL THEN
        SELECT d.college_id INTO NEW.college_id
          FROM attendance.sections s
          JOIN attendance.departments d ON d.department_id = s.department_id
         WHERE s.section_id = NEW.section_id;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_student_college BEFORE INSERT OR UPDATE OF section_id, college_id ON identity.students
    FOR EACH ROW EXECUTE FUNCTION identity.set_student_college();


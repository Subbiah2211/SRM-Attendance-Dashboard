    period_id          integer,
    classroom_id       integer,
    semester_id        integer,
    scheduled_staff_id bigint,
    staff_id           bigint,
    status             text
)
    LANGUAGE sql STABLE
    AS $$
    SELECT g.day::date,
           t.timetable_id,
           dep.college_id,
           sec.department_id,
           t.section_id,
           t.subject_id,
           t.period_id,
           t.classroom_id,
           t.semester_id,
           t.staff_id,
           COALESCE(cs.staff_id, sw.replacement_staff_id, t.staff_id),
           COALESCE(cs.status, 'scheduled')
    FROM generate_series(p_from::timestamp, p_to::timestamp, interval '1 day') AS g(day)
    JOIN attendance.timetable t
      ON t.day_of_week = EXTRACT(ISODOW FROM g.day)::integer
     AND t.effective_from <= g.day::date
     AND (t.effective_to IS NULL OR t.effective_to >= g.day::date)
    JOIN attendance.semesters sem
      ON sem.semester_id = t.semester_id
     AND g.day::date BETWEEN sem.start_date AND sem.end_date
    JOIN attendance.sections sec ON sec.section_id = t.section_id
    JOIN attendance.departments dep ON dep.department_id = sec.department_id
    LEFT JOIN attendance.class_swaps sw
      ON sw.timetable_id = t.timetable_id AND sw.swap_date = g.day::date AND sw.status = 'approved'
    LEFT JOIN attendance.class_sessions cs
      ON cs.timetable_id = t.timetable_id AND cs.session_date = g.day::date
    WHERE (p_college_id IS NULL OR dep.college_id = p_college_id)
      AND NOT EXISTS (
            SELECT 1 FROM attendance.holidays h
             WHERE h.academic_year_id = t.academic_year_id AND h.holiday_date = g.day::date)
      AND NOT EXISTS (
            SELECT 1 FROM attendance.working_days w
             WHERE w.academic_year_id = t.academic_year_id AND w.work_date = g.day::date AND NOT w.is_working);
$$;
COMMENT ON FUNCTION attendance.sessions_between(date, date, integer) IS 'Every class that should run between two dates: timetable versions in effect, minus holidays, with substitutions applied. day_of_week is ISO: 1 = Monday.';

-- ---------------------------------------------------------------------
-- 14. Reporting views: college and semester columns, thresholds from settings
-- ---------------------------------------------------------------------
DROP VIEW attendance.vw_defaulters;
DROP VIEW attendance.vw_student_attendance;
DROP VIEW attendance.vw_daily_report;

CREATE VIEW attendance.vw_daily_report AS
 SELECT r.attendance_date,
        sub.subject_name,
        sec.section_name,
        count(*) FILTER (WHERE r.status IN ('present', 'late')) AS present,
        count(*) FILTER (WHERE r.status = 'late')               AS late,
        count(*) FILTER (WHERE r.status = 'absent')             AS absent,
        count(*) FILTER (WHERE r.status = 'excused')            AS excused,
        sub.college_id,
        sec.department_id,
        t.semester_id,
        sec.section_id,
        sub.subject_id
   FROM attendance.records r
   JOIN attendance.timetable t   ON t.timetable_id = r.timetable_id
   JOIN attendance.subjects sub  ON sub.subject_id = t.subject_id
   JOIN attendance.sections sec  ON sec.section_id = t.section_id
  GROUP BY r.attendance_date, sub.subject_id, sub.subject_name, sub.college_id,
           sec.section_id, sec.section_name, sec.department_id, t.semester_id;

CREATE VIEW attendance.vw_student_attendance AS
 SELECT s.student_id,
        s.university_id,
        s.full_name,
        sub.subject_name,
        count(r.attendance_id) AS total,
        count(r.attendance_id) FILTER (WHERE r.status IN ('present', 'late')) AS attended,
        attendance.pct(
            (count(r.attendance_id) FILTER (WHERE r.status IN ('present', 'late')))::integer,
            (count(r.attendance_id) FILTER (WHERE r.status = 'excused'))::integer,
            count(r.attendance_id)::integer,
            s.college_id) AS percentage,
        s.college_id,
        t.semester_id,
        sub.subject_id,
        s.section_id
   FROM identity.students s
   LEFT JOIN attendance.records r   ON r.student_id = s.student_id
   LEFT JOIN attendance.timetable t ON t.timetable_id = r.timetable_id
   LEFT JOIN attendance.subjects sub ON sub.subject_id = t.subject_id
  GROUP BY s.student_id, s.university_id, s.full_name, s.college_id, s.section_id,
           sub.subject_id, sub.subject_name, t.semester_id;

CREATE VIEW attendance.vw_defaulters AS
 SELECT student_id, university_id, full_name, subject_name, total, attended, percentage,
        college_id, semester_id, subject_id, section_id
   FROM attendance.vw_student_attendance
  WHERE percentage < attendance.setting(college_id, 'defaulter_threshold_pct', '75')::numeric;

